#!/usr/bin/env python3
"""Regenerate k8s/cluster/01-configmap.yaml from configs/docker/cluster/.

The Kubernetes ConfigMap is the compose cluster config with the peer names
swapped for the StatefulSet's stable pod DNS names, so the two can't drift.
Run from the repo root: python3 scripts/gen-k8s-cluster-config.py
"""
col = open('configs/docker/cluster/collector.yaml').read()
col = col.replace("docker-compose.cluster.yml", "k8s/cluster (StatefulSet)").replace(
    "(NODE_ID, set per service in the compose file)", "(NODE_ID, set from the pod name)")
edge = open('configs/docker/cluster/edge.yaml').read().replace(
    "docker-compose.cluster.yml", "the k8s cluster overlay")
for i, n in ((1, 0), (2, 1), (3, 2)):
    col = col.replace(
        f'id: cluster-{i}, addr: "cluster-{i}:8301", client_addr: "cluster-{i}:8311"',
        f'id: collector-{n}, addr: "collector-{n}.collector-raft:8301", client_addr: "collector-{n}.collector-raft:8311"')
    edge = edge.replace(f'cluster-{i}:7000', f'collector-{n}.collector-raft:7000')


def ind(t):
    return "".join("    " + l if l.strip() else l for l in t.splitlines(True))


open('k8s/cluster/01-configmap.yaml', 'w').write(
    """# Generated by scripts/gen-k8s-cluster-config.py from configs/docker/cluster/
# (collector.yaml/edge.yaml with the peer names swapped for the StatefulSet's
# stable pod DNS names). Don't hand-edit the data: block.
apiVersion: v1
kind: ConfigMap
metadata:
  name: logflow-cluster-configs
  namespace: logflow-cluster
data:
  collector.yaml: |
""" + ind(col) + "  edge.yaml: |\n" + ind(edge))
